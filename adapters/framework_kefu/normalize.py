"""
adapters.framework_kefu.normalize — 命中比对的确定性归一化（docs/10 §10.3）

职责：给"文本档逐字相等"这一个判定提供两侧同口径的文本表示——只有四步，纯函数。
不负责：不做语义分析、不做命中判定、不产生事件、不读写任何文件。

四步（顺序冻结，docs/10 §10.3）：
    ① 去除首尾与内部所有空白字符（含全角空格 U+3000）
    ② 全角 ↔ 半角（ASCII 可见区 FF01–FF5E + 常见全角标点 ，。？！：；（） ）
    ③ Unicode NFKC（兼容字符：①/²/ﬁ/℃…）
    ④ 小写

WHY 只准这四步、不许加步：
    归一化是"逐字相等"唯一被允许的松弛，它必须是确定性、可复核、可单测的。
    同义改写 / 去语气词 / 去标点后比较 属于语义操作，一旦放进这里就等于自造命中——
    会把"您好"当成"您好。"播出来，正是红线举的"播了差不多但不是这句的话"，
    而且事后无法定位（docs/10 §10.2 裁定 1）。所以本函数只做字符级映射，
    语义层面的差异（包括标点有无）一律保留，交给"逐字相等"自然判为未命中。
"""

import unicodedata

# ---------------------------------------------------------------------------
# 步骤 ② 的映射表（模块级常量，保证同输入必得同输出）
# ---------------------------------------------------------------------------

# 常见全角标点 → 半角（docs/10 §10.3 逐个点名，必须显式列出）。
# 这 8 个里有 7 个落在 FF01–FF5E 区间，会被下面的区间平移自动覆盖；
# "。"（U+3002，CJK 标点区）不在区间内——虽然 NFKC 也会把它折成 "."，
# 但按规格它属于步骤 ② 的映射范围，显式列出可让四步各自独立可测。
_PUNCT_MAP = {
    ord("，"): ",",
    ord("。"): ".",
    ord("？"): "?",
    ord("！"): "!",
    ord("："): ":",
    ord("；"): ";",
    ord("（"): "(",
    ord("）"): ")",
}

# 合并成一张 str.translate 用的表：显式标点优先，其余 ASCII 可见区走区间平移
_TRANS_TABLE = dict(_PUNCT_MAP)
for _cp in range(0xFF01, 0xFF5F):      # Ａ…～ → A…~（含全角数字、字母、常见符号）
    _TRANS_TABLE.setdefault(_cp, chr(_cp - 0xFEE0))


def normalize_text(text: str) -> str:
    """把一句话归一到"逐字相等"可比的表示。纯函数，同输入必得同输出。

    参数：
        text: 待归一文本（str）

    返回：
        归一化后的文本（str；输入为空串时返回空串，不返回 None）

    异常：
        TypeError: text 不是 str（禁止把 None/bytes 静默当空串处理）
    """
    if not isinstance(text, str):
        # WHY：None 往往是"上游没给文本"，把它当空串会让"没命中"伪装成"命中空话术"
        raise TypeError(
            f"normalize_text 需要 str，实际为 {type(text).__name__}({text!r})"
        )

    s = text

    # ① 去所有空白：isspace() 覆盖 ASCII 空白、\t/\n、以及全角空格 U+3000
    #    WHY 连内部空白一起去：ASR 与 LLM 都可能插空格，空格属于书写噪声而非语义
    s = "".join(ch for ch in s if not ch.isspace())

    # ② 全角 ↔ 半角（只做映射，不增删字符）
    s = s.translate(_TRANS_TABLE)

    # ③ NFKC：处理 ①/²/ﬁ/℃/㈱ 这类"长得一样但码位不同"的兼容字符
    s = unicodedata.normalize("NFKC", s)

    # ④ 大小写统一（小写）
    s = s.lower()

    return s
